import { expect, test } from '@playwright/test';

test.skip(process.env.CURATION_DATABASE_FIXTURE !== '1', 'Requires isolated PostgreSQL backend fixture on 8100 and admin Vite on 5176');
test('admin curated queue persists, controls public order and handles conflicts', async ({ page, context, request }, info) => {
  const api = 'http://127.0.0.1:8100/api/admin/homepage/featured';
  const headers = { 'X-Admin-Key': 'test-admin' };
  const queue = await (await request.get(api, { headers })).json();
  await request.put(api, { headers, data: { prompt_ids: [], revision: queue.revision } });
  await context.addInitScript(() => sessionStorage.setItem('admin_key', 'test-admin'));
  await page.setViewportSize({ width: 1536, height: 1024 });
  await page.goto('http://127.0.0.1:5176/homepage');
  await expect(page.getByRole('heading', { name: '首页推荐', exact: true })).toBeVisible();
  const candidate = (title: string) => page.locator('.homepage-candidate').filter({ hasText: title });
  for (const title of ['精选测试作品 25', '精选测试作品 24']) await candidate(title).getByRole('button', { name: '加入推荐' }).click();
  const rows = page.locator('.homepage-row .homepage-title');
  await expect(rows).toHaveText(['精选测试作品 25', '精选测试作品 24']);
  await page.getByRole('button', { name: '上移 精选测试作品 24' }).click();
  await expect(rows).toHaveText(['精选测试作品 24', '精选测试作品 25']);
  await page.getByRole('button', { name: '下移 精选测试作品 24' }).click();
  await expect(rows).toHaveText(['精选测试作品 25', '精选测试作品 24']);
  const handle = page.getByRole('button', { name: '拖拽排序 精选测试作品 25' });
  await expect(page.locator('.homepage-row').first()).toHaveCSS('transform', 'none');
  await handle.focus(); await page.keyboard.press('Space');
  await expect(handle).toHaveAttribute('aria-pressed', 'true');
  // Dnd-kit measures droppable rectangles after activation on the next paint.
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await page.keyboard.press('ArrowDown');
  await expect(page.getByRole('status').filter({ hasText: 'was moved over droppable area 00000000-0000-0000-0000-00000000007c' })).toBeVisible();
  await page.keyboard.press('Space');
  await expect(rows).toHaveText(['精选测试作品 24', '精选测试作品 25']);
  const first = await page.getByRole('button', { name: '拖拽排序 精选测试作品 24' }).boundingBox();
  const second = await page.getByRole('button', { name: '拖拽排序 精选测试作品 25' }).boundingBox();
  await page.mouse.move(first!.x + 10, first!.y + 10); await page.mouse.down(); await page.mouse.move(second!.x + 10, second!.y + 35, { steps: 12 }); await page.mouse.up();
  await expect(rows).toHaveText(['精选测试作品 25', '精选测试作品 24']);
  // Wait for dnd-kit's post-drop click suppression to release before button sorting.
  await page.evaluate(() => new Promise(resolve => { let frames=0; const tick=()=>{ if (++frames>=6) resolve(null); else requestAnimationFrame(tick); }; requestAnimationFrame(tick); }));
  // Make curated order differ from popularity before saving.
  await page.getByRole('button', { name: '上移 精选测试作品 24' }).click();
  await expect(rows).toHaveText(['精选测试作品 24', '精选测试作品 25']);
  await page.getByRole('button', { name: '保存推荐' }).click();
  await expect(page.getByText('推荐顺序已保存，首页将按此顺序展示。')).toBeVisible();
  await page.reload(); await expect(rows).toHaveText(['精选测试作品 24', '精选测试作品 25']);
  if (info.project.name === 'mobile') await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '手机预览' }).click();
  const preview = page.locator('.homepage-preview');
  expect((await preview.boundingBox())!.width).toBeLessThanOrEqual(390);
  await page.screenshot({ path: `/tmp/homepage-admin-${info.project.name}.png`, fullPage: true });
  const home = await context.newPage(); await home.goto('http://127.0.0.1:3000/');
  await home.waitForLoadState('networkidle');
  const visibleCards = home.locator(`[data-layout="${info.project.name}"] a[aria-label^="查看提示词"]`);
  await expect(visibleCards).toHaveCount(20);
  const positions = await visibleCards.evaluateAll(elements => elements.map(element => { const box = element.getBoundingClientRect(); return { name: element.getAttribute('aria-label'), x: box.x, y: box.y }; }).sort((a,b) => a.y-b.y || a.x-b.x));
  expect(positions.slice(0, 2).map(item => item.name)).toEqual(['查看提示词：精选测试作品 24', '查看提示词：精选测试作品 25']);
  await home.screenshot({ path: `/tmp/homepage-public-${info.project.name}.png` });
  await visibleCards.last().scrollIntoViewIfNeeded();
  await expect(visibleCards).toHaveCount(28);
  const hrefs = await visibleCards.evaluateAll(elements => elements.map(element => element.getAttribute('href')));
  expect(new Set(hrefs).size).toBe(28);
  await home.goto('http://127.0.0.1:3000/?sort=popular');
  await home.waitForLoadState('networkidle');
  const popularPositions = await visibleCards.evaluateAll(elements => elements.map(element => { const box = element.getBoundingClientRect(); return { name: element.getAttribute('aria-label'), x: box.x, y: box.y }; }).sort((a,b) => a.y-b.y || a.x-b.x));
  expect(popularPositions[0].name).toBe('查看提示词：精选测试作品 25');
  const popular = await (await request.get('http://127.0.0.1:8100/api/prompts?sort=popular&page_size=20')).json();
  expect(popular.items[0].title).toBe('精选测试作品 25');
  const filtered = await (await request.get('http://127.0.0.1:8100/api/prompts?sort=recommended&category=portrait&page_size=20')).json();
  expect(filtered.items[0].title).toBe('精选测试作品 24');
  expect(filtered.items.every((item: { category: string }) => item.category === 'portrait')).toBe(true);
  await page.getByRole('button', { name: '移除 精选测试作品 25' }).click();
  await page.getByRole('button', { name: '保存推荐' }).click();
  await expect(rows).toHaveText(['精选测试作品 24']);
  await expect(page.getByRole('button', { name: '保存推荐' })).toBeDisabled();
  await page.reload();
  await expect(rows).toHaveText(['精选测试作品 24']);
  await candidate('精选测试作品 25').getByRole('button', { name: '加入推荐' }).click();
  await page.getByRole('button', { name: '保存推荐' }).click();
  await expect(page.getByRole('button', { name: '保存推荐' })).toBeDisabled();
  await page.getByRole('button', { name: '移除 精选测试作品 25' }).click();
  const current = await (await request.get(api, { headers })).json();
  await request.put(api, { headers, data: { prompt_ids: [], revision: current.revision } });
  await page.getByRole('button', { name: '保存推荐' }).click();
  await expect(page.getByRole('alert')).toContainText('你的更改仍保留');
  await expect(rows).toHaveText(['精选测试作品 24']);
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: '重新加载' }).click();
  await expect(rows).toHaveCount(0);
  const fallback = await (await request.get('http://127.0.0.1:8100/api/prompts?sort=recommended&page_size=20')).json();
  expect(fallback.items[0].title).toBe('精选测试作品 25');
  await home.close();
});
